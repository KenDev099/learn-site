// 第 2 課的測試資料（不用改）：在這一題專屬的 schema t_<slug> 複製一份咖啡店的四張表與資料。
// 課程的 public.orders 只開放給後台，這課還沒教權限，所以這份複本先讓 anon 讀全部、能新增訂單；第 3、4 課再把它收緊
import { applySql, taskSchema } from '../../helpers/supa.ts'

export async function cafeSchema(dir: string): Promise<string> {
  const schema = await taskSchema(dir)
  await applySql(schema, `
    create table customers (id integer generated by default as identity primary key, name text not null, phone text, city text);
    create table products (id integer generated by default as identity primary key, name text not null, price integer not null check (price > 0));
    create table orders (id integer generated by default as identity primary key,
      customer_id integer not null references customers (id), ordered_at timestamptz not null default now(), total integer not null);
    create table order_items (order_id integer not null references orders (id), product_id integer not null references products (id),
      quantity integer not null check (quantity > 0), unit_price integer not null, primary key (order_id, product_id));
    insert into customers select * from public.customers;
    insert into products select * from public.products;
    insert into orders select * from public.orders;
    insert into order_items select * from public.order_items;
    alter table customers alter column id restart with 100;
    alter table products alter column id restart with 100;
    alter table orders alter column id restart with 100;
    alter table customers enable row level security;
    alter table products enable row level security;
    alter table orders enable row level security;
    alter table order_items enable row level security;
    create policy "練習用：全部可讀" on customers for select to anon using (true);
    create policy "練習用：全部可讀" on products for select to anon using (true);
    create policy "練習用：全部可讀" on orders for select to anon using (true);
    create policy "練習用：全部可讀" on order_items for select to anon using (true);
    create policy "練習用：可新增" on orders for insert to anon with check (true);
    create policy "練習用：可新增" on order_items for insert to anon with check (true);
    grant select on customers, products, orders, order_items to anon;
    grant insert on orders, order_items to anon;`)
  return schema
}
