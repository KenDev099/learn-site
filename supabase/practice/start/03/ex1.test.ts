// 練習 1：GRANT＋RLS＋policy。測試用 publishable key（anon）與真的使用者 JWT（authenticated）透過 API 打
import { after, before, test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { applySql, clientFor, createUser, deleteUsers, dropTaskSchema, requireStack, sql, taskSchema, type TestUser } from '../../helpers/supa.ts'

const dir = import.meta.dirname
let schema: string
let a: TestUser, b: TestUser
before(async () => {
  requireStack(['db', 'kong', 'rest', 'auth'])
  schema = await taskSchema(dir)
  await applySql(schema, `
    create table products (id integer generated by default as identity primary key, name text not null, price integer not null);
    insert into products (name, price) select name, price from public.products order by id;
    create table orders (id integer generated always as identity primary key,
      customer_id uuid not null default auth.uid(), total integer not null, note text);`)
  await applySql(schema, readFileSync(join(dir, 'grants.sql'), 'utf8'))
  a = await createUser(dir, 'ex1_a')
  b = await createUser(dir, 'ex1_b')
})
after(async () => {
  if (schema) await dropTaskSchema(schema)
  await deleteUsers(dir)
})

const can = async (role: string, table: string, priv: string) =>
  (await sql(`select has_table_privilege($1, $2, $3) as ok`, [role, `${schema}.${table}`, priv]))[0].ok

test('沒登入（anon）和登入的人都讀得到 6 項菜單', async () => {
  const anon = await clientFor(schema).from('products').select('name')
  assert.equal(anon.error?.message, undefined, `anon 讀 products 失敗：${anon.error?.message}（42501 代表沒有 GRANT SELECT）`)
  assert.equal(anon.data?.length, 6, `anon 讀到 ${anon.data?.length} 筆：0 筆代表開了 RLS 但沒有讓 anon 看得到的 policy`)
  const user = await clientFor(schema, a).from('products').select('name')
  assert.equal(user.data?.length, 6, `登入的人讀到 ${user.data?.length} 筆（${user.error?.message ?? ''}）：policy 與 GRANT 都要包含 authenticated，登入之後就不是 anon 了`)
})

test('任何人都不能透過 API 改菜單（只給需要的權限，不要 grant all）', async () => {
  for (const role of ['anon', 'authenticated']) for (const priv of ['insert', 'update', 'delete', 'truncate'])
    assert.equal(await can(role, 'products', priv), false, `${role} 對 products 有 ${priv} 權限：菜單只要 grant select，不要 grant all`)
  const r = await clientFor(schema, a).from('products').update({ price: 1 }).eq('id', 1)
  assert.equal(r.error?.code, '42501', '登入的人改菜單價格應該被拒絕（42501）')
})

test('登入的人能用自己的身分下單', async () => {
  const r = await clientFor(schema, a).from('orders').insert({ total: 190 })
  assert.equal(r.error?.message, undefined, `登入的人新增訂單失敗：${r.error?.message}（42501 代表沒有 grant insert on orders to authenticated）`)
  const [row] = await sql(`select customer_id from ${schema}.orders order by id desc limit 1`)
  assert.equal(row?.customer_id, a.id, 'customer_id 預設是下單的人（auth.uid()）')
})

test('不能替別人下單（RLS 要開著，policy 才會生效）', async () => {
  const r = await clientFor(schema, a).from('orders').insert({ customer_id: b.id, total: 1 })
  assert.equal(r.error?.code, '42501', `用 A 的身分寫 customer_id = B 應該被拒絕，實際 ${r.error ? r.error.message : '成功了'}：沒開 RLS 時 policy 寫了也不會檢查`)
})

test('沒登入不能下單；訂單還不開放讀取', async () => {
  const r = await clientFor(schema).from('orders').insert({ total: 1, customer_id: a.id })
  assert.equal(r.error?.code, '42501', 'anon 新增訂單應該被拒絕（42501）：insert 只 grant 給 authenticated')
  for (const role of ['anon', 'authenticated']) for (const priv of ['select', 'update', 'delete', 'truncate'])
    assert.equal(await can(role, 'orders', priv), false, `${role} 對 orders 有 ${priv} 權限：這一題訂單只開放 authenticated 新增`)
})

test('兩張表都開了 RLS', async () => {
  const rows = await sql(`select relname, relrowsecurity from pg_class where relnamespace = $1::regnamespace and relname in ('products', 'orders') order by relname`, [schema])
  for (const r of rows) assert.equal(r.relrowsecurity, true, `${r.relname} 沒開 RLS：alter table ${r.relname} enable row level security（沒開時 policy 不會生效，GRANT 給了什麼就能對每一列做什麼）`)
})
